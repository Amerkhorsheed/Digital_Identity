/// أسماء المحافظات فقط، بالترتيب الإداري.
List<String> get kGovernorateNames =>
    [for (final g in kSyrianGovernorates) g.name];

/// مدن محافظة بعينها، مع خيار «أخرى» في نهاية القائمة.
List<String> citiesOf(String? governorate) {
  if (governorate == null) return const [];
  for (final g in kSyrianGovernorates) {
    if (g.name == governorate) return [...g.cities, kOtherPlace];
  }
  return const [kOtherPlace];
}

/// المحافظة التي تتبع لها [city]، إن وُجدت.
String? governorateOf(String city) {
  for (final g in kSyrianGovernorates) {
    if (g.cities.contains(city)) return g.name;
  }
  return null;
}
